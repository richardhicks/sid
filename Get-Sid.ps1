<#

.SYNOPSIS
    Gets the Security Identifier (SID) of the current user or the local computer's domain account.

.PARAMETER SidType
    Specifies the type of SID to return - User or Machine. The default is User.

.EXAMPLE
    Get-Sid -SidType User

    Returns the SID for the current user.

.EXAMPLE
    Get-Sid -SidType Machine

    Returns the SID for the current computer's domain account.

.DESCRIPTION
    Use this function to retrieve the SID of the current user or the local computer. The user SID is read directly from the current process token. The machine SID is the SID of the computer's domain account (not the local machine SID) and requires the computer to be domain-joined.

.INPUTS
    None. This function does not accept pipeline input.

.OUTPUTS
    PSCustomObject with Principal and SID properties.

.LINK
    https://github.com/richardhicks/adcstools/blob/main/Functions/Get-Sid.ps1

