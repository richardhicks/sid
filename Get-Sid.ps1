[CmdletBinding()]
[OutputType([PSCustomObject])]

Param (

    [ValidateSet('User', 'Machine')]
    [string]$SidType = 'User'

)

# SID translation is only supported on Windows
If ($PSVersionTable.PSEdition -eq 'Core' -and -not $IsWindows) {

    Throw 'Get-Sid is only supported on Windows.'

}

# Establish security principal - user or device
Switch ($SidType) {

    'User' { $Principal = $env:USERNAME }
    'Machine' { $Principal = "${env:COMPUTERNAME}$" }

}

Write-Verbose "Identifying SID for $($SidType.ToLowerInvariant()) $Principal..."

Try {

    If ($SidType -eq 'User') {

        # Read the SID directly from the current process token - authoritative and requires no name resolution
        $Sid = [System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value

    }

    Else {

        # Resolves the computer's domain account - requires domain membership
        $Id = [System.Security.Principal.NTAccount]::new($Principal)
        $Sid = $Id.Translate([System.Security.Principal.SecurityIdentifier]).Value

    }

    [PSCustomObject]@{

        Principal = $Principal
        SID       = $Sid

    }

}

Catch {

    If ($SidType -eq 'Machine') {

        $Message = "Unable to translate machine account $Principal to a SID. Verify this computer is domain-joined and a domain controller is reachable."

    }

    Else {

        $Message = "Unable to translate user $Principal to a SID."

    }

    $Exception = [System.InvalidOperationException]::new($Message, $_.Exception)

    $PSCmdlet.WriteError(
        [System.Management.Automation.ErrorRecord]::new(
            $Exception,
            'SidTranslationFailed',
            [System.Management.Automation.ErrorCategory]::InvalidResult,
            $Principal
        )
    )

}

